"""Build MK Messages.
  python3 build.py OUT_DIR   -> writes index.html (repo root) and OUT_DIR/_worker.js
The Pages site is one worker script that serves the page + PWA files, so no static
asset store is needed.  MK_LOCAL=1 points the page at its own origin (for local tests)."""
import base64, json, os, re, sys
root = os.path.dirname(os.path.abspath(__file__))
rd = lambda p: open(os.path.join(root, p), encoding='utf-8').read()
js = '\n'.join(rd('web/' + n) for n in ['qrcode.js', 'core.js', 'features.js', 'call.js', 'ar.js', 'status.js', 'main.js'])
if os.environ.get('MK_LOCAL'):
    js = re.sub(r"const API='[^']*';", "const API=location.origin;", js, count=1)
html = rd('web/index.template.html').replace('/*CSS*/', rd('web/style.css')).replace('<!--BODY-->', rd('web/body.html')).replace('/*JS*/', js)
if not os.environ.get('MK_LOCAL'):
    open(os.path.join(root, 'index.html'), 'w', encoding='utf-8').write(html)
files = {
    '/': (None, 'text/html; charset=utf-8'),
    '/index.html': (None, 'text/html; charset=utf-8'),
    '/manifest.webmanifest': ('pwa/manifest.webmanifest', 'application/manifest+json'),
    '/sw.js': ('pwa/sw.js', 'application/javascript; charset=utf-8'),
    '/icon-192.png': ('pwa/icon-192.png', 'image/png'),
    '/icon-512.png': ('pwa/icon-512.png', 'image/png'),
    '/icon-maskable-512.png': ('pwa/icon-maskable-512.png', 'image/png'),
    '/apple-touch-icon.png': ('pwa/apple-touch-icon.png', 'image/png'),
}
table = {}
for url, (path, ctype) in files.items():
    binary = ctype == 'image/png'
    data = html.encode('utf-8') if path is None else open(os.path.join(root, path), 'rb').read()
    table[url] = {'t': ctype, 'b': binary, 'd': base64.b64encode(data).decode() if binary else data.decode('utf-8')}
out = """// Generated by build.py - serves MK Messages (page + PWA files) from one script.
const FILES = %s;
const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
export default {
  async fetch(request) {
    const f = FILES[new URL(request.url).pathname];
    if (!f && new URL(request.url).pathname === '/share') return Response.redirect(new URL('/', request.url).href, 303);
    if (!f) return new Response('Not found', { status: 404 });
    return new Response(f.b ? bytes(f.d) : f.d, { headers: { 'content-type': f.t, 'cache-control': 'no-cache' } });
  },
};
""" % json.dumps(table)
os.makedirs(sys.argv[1], exist_ok=True)
open(os.path.join(sys.argv[1], '_worker.js'), 'w', encoding='utf-8').write(out)
print('built', len(out), 'bytes; page', len(html))
